import { IsOptional, IsString } from 'class-validator';

// Доп. текстовое поле в том же multipart-запросе, что и audio (владелец
// 09.09.2026) — диктовка со страницы встречи получает её саммари как
// контекст (см. VoiceService.parse).
export class ParseVoiceDto {
  @IsOptional()
  @IsString()
  meetingId?: string;

  // Stage 2, Phase H.1 (внешний аудит 20.09.2026, P0) — раньше /voice/parse
  // не имел идемпотентности вовсе: сеть оборвалась после того, как реальная
  // мутация (создание/правка/удаление задачи или события) уже случилась, но
  // до того, как ответ дошёл до клиента — повторная отправка ТОГО ЖЕ уже
  // записанного аудио (например, автоматическим повтором на нестабильной
  // сети, не обязательно новой надиктовкой пользователя) выполнила бы
  // действие ещё раз. Клиент генерирует один раз на попытку отправки
  // (тот же принцип, что SendMessageDto.clientRequestId у текстового
  // чата) — см. VoiceService.parse про то, как именно используется.
  @IsOptional()
  @IsString()
  clientRequestId?: string;

  // Stage 2, Phase H.1 (внешний аудит 20.09.2026, P2) — раньше голос всегда
  // резолвил "последний активный разговор сотрудника"
  // (AssistantChatService.getOrCreatePrimaryConversation), не обязательно
  // тот, что открыт на экране прямо сейчас. Сегодня это не активный баг
  // (MVP — один разговор на сотрудника, UI выбора нескольких разговоров
  // нет), но перестаёт быть безопасным допущением с появлением нескольких
  // устройств/разговоров. Mini App передаёт свой conversationId явно, если
  // он уже известен экрану — сервер проверяет владение
  // (assertOwnedConversation, та же проверка, что у текстового чата) и
  // пишет именно туда, не полагаясь на эвристику "последний по updatedAt".
  @IsOptional()
  @IsString()
  conversationId?: string;
}
